const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const root = path.resolve(__dirname, '..');
const results = path.join(root, 'test-results');
const fixture = name => path.join(__dirname, 'fixtures', name);
(async () => {
  await fs.mkdir(results, { recursive: true });
  const env = { ...process.env, ATWREAD_TEST_USER_DATA: path.join(results, `profile-${Date.now()}`) };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: [root], env });
  const page = await app.firstWindow();
  page.setDefaultTimeout(25000);
  const errors = []; page.on('pageerror', error => { errors.push(error.message); console.log('PAGE ERROR:', error.stack); });
  page.on('console', msg => { if (msg.type() === 'error') console.log('Renderer:', msg.text()); });
  const open = async name => app.evaluate(({ BrowserWindow }, file) => BrowserWindow.getAllWindows()[0].webContents.send('open-request', file), fixture(name));
  try {
    await page.waitForFunction(() => !!window.reader && !!document.querySelector('#open')?.onclick);
    await page.screenshot({ path: path.join(results, '01-home.png') });
    await open('阅读示例.md');
    await page.waitForFunction(() => document.querySelector('#document-title').textContent === '阅读示例.md');
    assert.equal(await page.locator('#markdown h1').textContent(), '阅读，是一段安静的旅程');
    assert.equal(await page.locator('#markdown script').count(), 0);
    assert.equal(await page.evaluate(() => window.__injected), undefined);
    assert.equal(await page.locator('#status').count(), 1);
    assert.equal(await page.locator('#password-dialog').count(), 1);
    await page.waitForFunction(() => document.querySelector('#markdown img').naturalWidth === 600);
    await page.locator('#zoom').selectOption('1.5');
    assert.equal(await page.locator('#markdown').evaluate(el => getComputedStyle(el).fontSize), '24px');
    await page.locator('#zoom').selectOption('1');
    await page.screenshot({ path: path.join(results, '02-markdown.png') });
    await page.locator('#outline button').filter({ hasText: '一段代码' }).click();
    await page.waitForFunction(() => document.querySelector('#md-container').scrollTop > 100);
    await open('阅读示例.pdf');
    await page.waitForFunction(() => document.querySelector('#page-total').textContent === '/ 3');
    await page.waitForFunction(() => document.querySelector('#pdf-viewer canvas')?.width > 0);
    await page.locator('#pdf-viewer .textLayer span').first().waitFor();
    await page.screenshot({ path: path.join(results, '03-pdf.png') });
    await page.locator('#next').click();
    await page.waitForFunction(() => document.querySelector('#page-number').value === '2');
    await page.locator('#page-number').fill('3'); await page.locator('#page-number').press('Enter');
    await page.waitForFunction(() => document.querySelector('#progress').textContent.includes('3 / 3'));
    await page.locator('#zoom').selectOption('1.5');
    await page.locator('#zoom').selectOption('page-fit');
    await page.locator('#outline button').first().click();
    await page.waitForFunction(() => document.querySelector('#page-number').value === '1');
    await open('加密.pdf');
    await page.locator('#password-dialog').waitFor({ state: 'visible' });
    await page.locator('#password').fill('wrong'); await page.locator('#password-form').evaluate(form => form.requestSubmit());
    await page.waitForFunction(() => document.querySelector('#password-message').textContent.includes('不正确'));
    await page.locator('#password').fill('atw-test'); await page.locator('#password-form').evaluate(form => form.requestSubmit());
    await page.waitForFunction(() => document.querySelector('#document-title').textContent === '加密.pdf');
    await page.locator('#password-dialog').waitFor({ state: 'hidden' });
    await open('加密.pdf'); await page.locator('#password-dialog').waitFor({ state: 'visible' });
    await page.locator('#password-cancel').click();
    await page.locator('#welcome').waitFor({ state: 'visible' });
    await open('损坏.pdf');
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('损坏'));
    await open('不存在.md');
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('不存在'));
    // Native file dialog acceptance and cancellation are exercised through its Electron API.
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, fixture('阅读示例.md'));
    await page.locator('#open').click();
    await page.waitForFunction(() => document.querySelector('#document-title').textContent === '阅读示例.md');
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
    await page.locator('#open').click();
    assert.equal(await page.locator('#document-title').textContent(), '阅读示例.md');
    await page.evaluate(() => { const input = document.createElement('input'); input.type = 'file'; input.id = 'test-drop'; document.body.append(input); });
    await page.locator('#test-drop').setInputFiles(fixture('阅读示例.pdf'));
    await page.evaluate(() => { const input = document.querySelector('#test-drop'); const transfer = new DataTransfer(); transfer.items.add(input.files[0]); document.dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true })); input.remove(); });
    await page.waitForFunction(() => document.querySelector('#document-title').textContent === '阅读示例.pdf');
    // Rapid replacement must leave the last requested document active.
    await open('阅读示例.pdf'); await open('阅读示例.md');
    await page.waitForFunction(() => document.querySelector('#document-title').textContent === '阅读示例.md');
    await page.locator('#toggle-sidebar').click();
    assert(await page.locator('body').evaluate(el => el.classList.contains('sidebar-hidden')));
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(850, 640));
    await page.screenshot({ path: path.join(results, '04-small-window.png') });
    assert.deepEqual(errors, [], 'renderer has no unhandled JS errors');
    await fs.writeFile(path.join(results, 'result.json'), JSON.stringify({ passed: true, checks: ['home','Chinese Markdown','sanitization','heading isolation','local images','MD zoom','TOC','PDF canvas and text','PDF navigation','PDF zoom','password retry','password cancel','corrupt file','missing file','dialog accept/cancel','native file drop','rapid switching','sidebar','small window'], errors }, null, 2));
    console.log('PASS: 19 application checks including native file drop; no unhandled renderer errors.');
  } catch (error) {
    console.log('URL:', page.url(), 'Errors:', errors);
    await page.screenshot({ path: path.join(results, 'failure.png') });
    throw error;
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
